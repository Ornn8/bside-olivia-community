"""Content-free writer rejection vocabulary shared by diagnostics and telemetry."""
DECISION_REJECTION_REASONS = frozenset({
    'UNKNOWN', 'JSON_SYNTAX', 'FIELDS', 'VALUE_TYPE_OR_TIME', 'TEXT_OR_SKIP_TYPE',
    'DELIVERY_OR_LISTENING', 'EMPTY_OR_SKIPPED_REPLY', 'CONTROL_MARKER',
    'CONTROL_BODY_INVALID', 'CONTROL_BODY_DEPTH', 'SILENCE_INVALID', 'SILENCE_UNSUPPORTED',
    'SILENCE_NOT_AUTHORIZED', 'MEDIA_WITHOUT_PLAN', 'RECOVERY_ACTION_WITHOUT_PLAN',
    'REPEATED_REPLY', 'FOLLOWUP_CONFLICT', 'STICKER_TYPE', 'UNSUPPORTED_PREFERENCE_CHANGE',
    'QUIET_HOURS', 'EVIDENCE_TYPE', 'PAUSE_CONFLICT', 'PREFERENCES', 'TIME_RANGE',
})


def decision_rejection_reason(value):
    return value if isinstance(value, str) and value in DECISION_REJECTION_REASONS else 'UNKNOWN'
